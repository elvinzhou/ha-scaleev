#!/usr/bin/env python3
"""Interactive setup for ha-scaleev.

Logs in to your ScaleEV network, lets you pick a location/station/connector,
asks for the target energy and the Home Assistant entities to use, then writes
the Home Assistant files for you. Standard library only (Python 3.9+).

    python3 setup.py [--config-dir /path/to/ha/config] [--api-base URL]

Your password is only used to log in and to write secrets.yaml; set
SCALEEV_PASSWORD to skip the prompt.
"""
import argparse
import getpass
import json
import os
import re
import shutil
import sys
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
DEFAULT_API = "https://api-scaleev.demo.scaletech.xyz"
ENTITY_RE = r"[a-z_]+\.[a-z0-9_]+"


class SetupError(Exception):
    pass


def call(method, url, token=None, body=None):
    headers = {
        "accept": "application/json",
        "user-agent": "ha-scaleev-setup",
        "ngrok-skip-browser-warning": "true",
    }
    data = None
    if body is not None:
        data = json.dumps(body).encode()
        headers["content-type"] = "application/json"
    if token:
        headers["authorization"] = f"Bearer {token}"
    req = urllib.request.Request(url, data=data, headers=headers, method=method)
    try:
        with urllib.request.urlopen(req, timeout=20) as resp:
            payload = json.load(resp)
    except urllib.error.HTTPError as e:
        try:
            msg = json.load(e).get("message", "")
        except Exception:
            msg = ""
        raise SetupError(f"HTTP {e.code} from {url}: {msg}".strip())
    except (urllib.error.URLError, TimeoutError, ValueError) as e:
        raise SetupError(f"Could not reach {url}: {e}")
    if not isinstance(payload, dict) or payload.get("success") is not True:
        raise SetupError(f"Unexpected response from {url}")
    return payload.get("data")


def ask(prompt, default=None, pattern=None, secret=False):
    while True:
        suffix = f" [{default}]" if default not in (None, "") else ""
        text = f"{prompt}{suffix}: "
        value = getpass.getpass(text) if secret else input(text)
        value = value.strip() or (default or "")
        if not value:
            print("  A value is required.")
        elif pattern and not re.fullmatch(pattern, value):
            print("  That doesn't look right, try again.")
        else:
            return value


def ask_number(prompt, default=None):
    while True:
        raw = ask(prompt, default=None if default is None else str(default))
        try:
            n = float(raw)
            if 0 < n <= 250:
                return int(n) if n == int(n) else n
        except ValueError:
            pass
        print("  Enter a number between 1 and 250.")


def choose(title, items, label):
    if not items:
        raise SetupError(f"No {title.lower()} available for this account.")
    if len(items) == 1:
        print(f"{title}: {label(items[0])} (only option)")
        return items[0]
    print(f"\n{title}:")
    for i, item in enumerate(items, 1):
        print(f"  {i}) {label(item)}")
    while True:
        raw = input("Choose a number: ").strip()
        if raw.isdigit() and 1 <= int(raw) <= len(items):
            return items[int(raw) - 1]


def parse_link(link):
    """Return (tenant_domain, api_base_guess) from a link like https://collectron.scaleev.scaletech.xyz/map."""
    link = link.strip()
    host = urllib.parse.urlparse(link if "//" in link else f"//{link}").hostname or ""
    if not host:
        raise SetupError("Could not read a host name from that link.")
    domain = host.split(".")[0]
    api = DEFAULT_API if host.endswith(".scaleev.scaletech.xyz") else None
    return domain, api


def yq(value):
    return json.dumps(str(value), ensure_ascii=False)


def write_secrets(path, values):
    keep = []
    if path.exists():
        shutil.copy(path, path.with_name(path.name + ".bak"))
        keep = [l for l in path.read_text().splitlines() if not l.startswith("scaleev_")]
    lines = keep + ([""] if keep and keep[-1] else []) + [f"{k}: {yq(v)}" for k, v in values.items()]
    path.write_text("\n".join(lines) + "\n")
    try:
        path.chmod(0o600)
    except OSError:
        pass


def automation_yaml(cfg):
    return f"""# Generated by ha-scaleev setup.py - safe to edit.
automation:
  - id: scaleev_start_on_plug_in
    alias: ScaleEV - start charging on plug-in
    use_blueprint:
      path: scaleev/start_on_plug_in.yaml
      input:
        cable_sensor: {cfg['cable_sensor']}
        vehicle_tracker: {cfg['vehicle_tracker']}
        charge_zone: {cfg['charge_zone']}
        target_kwh: {cfg['target_kwh']}
        station_id: {yq(cfg['station_id'])}
        connector_id: {cfg['connector_id']}
        notify_service: {cfg['notify_service']}
        pay_timeout_minutes: {cfg['pay_timeout']}
"""


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--config-dir", help="Home Assistant config directory (or any folder to write into)")
    ap.add_argument("--api-base", help="ScaleEV API base URL if it can't be guessed from your link")
    args = ap.parse_args(argv)

    print("ha-scaleev setup\n")
    print("Paste any link from your charging network's web app, e.g. https://yournetwork.scaleev.scaletech.xyz/map")
    domain, guess = parse_link(ask("Link"))
    api = (args.api_base or guess or ask("API base URL (see README)", pattern=r"https?://\S+")).rstrip("/")
    tenant = call("GET", f"{api}/public/tenants/{urllib.parse.quote(domain)}/config")
    slug = tenant.get("slug")
    if not slug:
        raise SetupError("Network config did not include a tenant slug.")
    print(f"Found network: {tenant.get('appName', slug)}")

    email = ask("Account email")
    password = os.environ.get("SCALEEV_PASSWORD") or ask("Password", secret=True)
    login = call("POST", f"{api}/drivers/auth/login",
                 body={"email": email, "password": password, "tenantSlug": slug})
    token = login["access_token"]
    print(f"Logged in as {login['driver'].get('firstName', email)}.")

    locations = call("GET", f"{api}/drivers/locations", token=token)
    loc = choose("Location", locations, lambda l: f"{l['name']} - {l.get('address', '')} ({l.get('stationCount', '?')} stations)")
    stations = call("GET", f"{api}/drivers/locations/{loc['id']}/stations", token=token)
    stations = sorted(stations, key=lambda s: s.get("name", ""))
    st = choose("Station", stations,
                lambda s: f"{s['name']} - {s.get('type', '')} {s.get('maxPower', '?')} kW, {s.get('status', '?')}")
    conn = choose("Connector", st.get("connectors") or [],
                  lambda c: f"#{c['connectorId']} {c.get('type', '')} {c.get('maxPower', '?')} kW")

    print("\nTarget energy: set this to your vehicle's usable battery capacity so the session isn't cut short.")
    kwh = ask_number("Target energy (kWh)")
    print("\nHome Assistant entities (find them under Settings > Devices & services > Entities):")
    cfg = {
        "station_id": st["id"],
        "connector_id": conn["connectorId"],
        "target_kwh": kwh,
        "cable_sensor": ask("Charge-cable-connected binary sensor", pattern=r"binary_sensor\.[a-z0-9_]+"),
        "vehicle_tracker": ask("Vehicle device tracker", pattern=r"device_tracker\.[a-z0-9_]+"),
        "charge_zone": ask("Zone where you charge", default="zone.home", pattern=r"zone\.[a-z0-9_]+"),
        "notify_service": ask("Notify action", default="notify.notify", pattern=r"notify\.[a-z0-9_]+"),
        "pay_timeout": 10,
    }

    out = Path(args.config_dir or ask("Home Assistant config directory (or a folder to write files into)",
                                       default="./scaleev-output")).expanduser()
    (out / "packages").mkdir(parents=True, exist_ok=True)
    bp = out / "blueprints" / "automation" / "scaleev"
    bp.mkdir(parents=True, exist_ok=True)
    shutil.copy(HERE / "packages" / "scaleev.yaml", out / "packages" / "scaleev.yaml")
    shutil.copy(HERE / "blueprints" / "automation" / "scaleev" / "start_on_plug_in.yaml", bp / "start_on_plug_in.yaml")
    (out / "packages" / "scaleev_automation.yaml").write_text(automation_yaml(cfg))
    write_secrets(out / "secrets.yaml", {
        "scaleev_api_base": api, "scaleev_tenant_slug": slug,
        "scaleev_email": email, "scaleev_password": password})

    print(f"\nWrote files to {out}:")
    for p in ("packages/scaleev.yaml", "packages/scaleev_automation.yaml",
              "blueprints/automation/scaleev/start_on_plug_in.yaml", "secrets.yaml"):
        print(f"  {p}")
    conf = out / "configuration.yaml"
    if not conf.exists() or "packages" not in conf.read_text():
        print("\nAdd this to configuration.yaml so packages are loaded:\n"
              "  homeassistant:\n    packages: !include_dir_named packages")
    print("\nNext: restart Home Assistant (or run Check configuration first).")
    print("Payment: the first session returns a Stripe checkout link. You'll get a 'Pay now' notification;")
    print("complete it once. Cards can't be linked through the API, so this is the only manual step.")


if __name__ == "__main__":
    try:
        main()
    except (SetupError, KeyboardInterrupt, EOFError) as e:
        print(f"\nSetup stopped: {e}" if str(e) else "\nSetup cancelled.", file=sys.stderr)
        sys.exit(1)
